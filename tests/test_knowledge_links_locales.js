'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const specialty = require('../news-app-2-specialty.js');
const media = require('../news-app-2-media.js');
const load = name => JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'..',name),'utf8'));
const sandbox = {window:{},document:{addEventListener(){}},console};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'..','lexicon-tab.js'),'utf8'),sandbox);
const snapshot = sandbox.window.WRNLexicon184.snapshot();
