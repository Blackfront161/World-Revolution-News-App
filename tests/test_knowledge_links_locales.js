const episodes=load('podcasts.json').map(media.normalizePodcast);
const links=()=>specialty.knowledgePodcastsForCatalog(paths,episodes,snapshot.terms).flatMap(p=>p.podcastEntries);
assert.equal(links().length,7,'all editorial links must resolve against runtime-normalized episodes');
const first=links()[0];
assert.equal(specialty.knowledgePodcastsForCatalog(paths,episodes.filter(e=>e.id!==first.episodeId),snapshot.terms).flatMap(p=>p.podcastEntries).length,6,'withdrawn episodes must hide contextual links');
assert(!specialty.knowledgePodcastsForCatalog(paths,episodes,snapshot.terms.filter(t=>!first.termIds.includes(t.id))).flatMap(p=>p.podcastEntries).some(e=>e.episodeId===first.episodeId));
