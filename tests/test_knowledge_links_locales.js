const revokedDirectories=load('media-directory-sources.json'); revokedDirectories.sources[0].status='revoked';
assert.equal(specialty.mediaDirectories(revokedDirectories).length,1);
const revokedTerms=structuredClone(snapshot.terms); revokedTerms.find(t=>t.id===first.termIds[0]).status='revoked';
assert(!specialty.knowledgePodcastsForCatalog(paths,episodes,revokedTerms).flatMap(p=>p.podcastEntries).some(e=>e.episodeId===first.episodeId));
assert.equal(specialty.mediaDirectories({...revokedDirectories,sources:[]}).length,0);
assert.equal(specialty.mediaDirectories({schema:'wrn.media-directories.v1',rights:'metadata-and-original-links-only',sources:[{id:'bad',name:'bad',url:'https://secret@example.com',feedConfirmed:false}]}).length,0);
